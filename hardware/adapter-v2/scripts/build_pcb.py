def remove_expr(text,start):
    depth=0; quoted=False; esc=False
    for j in range(start,len(text)):
        c=text[j]
        if quoted:
            if esc:esc=False
            elif c=='\\':esc=True
            elif c=='"':quoted=False
        elif c=='"':quoted=True
        elif c=='(':depth+=1
        elif c==')':
            depth-=1
            if depth==0:return text[:start]+text[j+1:]
    raise ValueError('Unbalanced footprint')

